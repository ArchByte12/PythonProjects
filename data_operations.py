# data_operations.py
# This module contains all the core mathematical functions.
# It is completely independent of how the results are displayed.

def add_numbers(a, b):
    """Calculates the sum of two numbers."""
    print(f"DEBUG: Executing addition logic for {a} + {b}")
    return a + b

def subtract_numbers(a, b):
    """Calculates the difference between two numbers."""
    print(f"DEBUG: Executing subtraction logic for {a} - {b}")
    return a - b

def multiply_numbers(a, b):
    """Calculates the product of two numbers."""
    print(f"DEBUG: Executing multiplication logic for {a} * {b}")
    return a * b

# Note: No print statements or I/O related to formatting are here.
